const languageToggle = document.querySelector('.language-toggle');
const savedLanguage = localStorage.getItem('language');
let currentLanguage = savedLanguage === 'it' ? 'it' : 'en';

const applyLanguage = (language) => {
  currentLanguage = language;
  document.documentElement.lang = language;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.getAttribute('data-i18n');
    const translation = translations[language][key];
    if (translation) {
      element.textContent = translation;
    }
  });

  document.querySelectorAll('[data-i18n-content]').forEach((element) => {
    const key = element.getAttribute('data-i18n-content');
    const translation = translations[language][key];
    if (translation) {
      element.setAttribute('content', translation);
    }
  });

  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    const key = element.getAttribute('data-i18n-aria');
    const translation = translations[language][key];
    if (translation) {
      element.setAttribute('aria-label', translation);
    }
  });

  languageToggle?.setAttribute('aria-label', translations[language][language === 'en' ? 'switchToItalian' : 'switchToEnglish']);
  languageToggle?.setAttribute('title', translations[language][language === 'en' ? 'switchToItalian' : 'switchToEnglish']);
  const flag = languageToggle?.querySelector('[aria-hidden="true"]');
  if (flag) {
    flag.textContent = language === 'en' ? '🇮🇹' : '🇬🇧';
  }

  const menuToggle = document.querySelector('.menu-toggle');
  const isMenuOpen = menuToggle?.getAttribute('aria-expanded') === 'true';
  menuToggle?.querySelector('.visually-hidden').replaceChildren(
    document.createTextNode(translations[language][isMenuOpen ? 'closeMenu' : 'openMenu']),
  );
};

applyLanguage(currentLanguage);

languageToggle?.addEventListener('click', () => {
  const nextLanguage = currentLanguage === 'en' ? 'it' : 'en';
  localStorage.setItem('language', nextLanguage);
  applyLanguage(nextLanguage);
  updateThemeToggle();
});

const menuToggle = document.querySelector('.menu-toggle');
const menu = document.querySelector('#menu');

if (menuToggle instanceof HTMLButtonElement && menu instanceof HTMLElement) {
  const closeMenu = () => {
    menu.classList.remove('is-open');
    menuToggle.setAttribute('aria-expanded', 'false');
    menuToggle.querySelector('.visually-hidden').textContent = translations[currentLanguage].openMenu;
  };

  menuToggle.addEventListener('click', () => {
    const isOpen = menuToggle.getAttribute('aria-expanded') === 'true';
    menu.classList.toggle('is-open', !isOpen);
    menuToggle.setAttribute('aria-expanded', String(!isOpen));
    menuToggle.querySelector('.visually-hidden').textContent = translations[currentLanguage][isOpen ? 'openMenu' : 'closeMenu'];
  });

  menu.querySelectorAll('a').forEach((link) => link.addEventListener('click', closeMenu));
  document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') {
      closeMenu();
    }
  });
}

const themeToggle = document.querySelector('.theme-toggle');
const themeLabel = themeToggle?.querySelector('.theme-label');
const savedTheme = localStorage.getItem('theme');

if (savedTheme === 'light') {
  document.documentElement.dataset.theme = 'light';
}

const updateThemeToggle = () => {
  const isDark = document.documentElement.dataset.theme !== 'light';
  themeToggle?.setAttribute('aria-pressed', String(isDark));
  themeToggle?.setAttribute(
    'aria-label',
    translations[currentLanguage][isDark ? 'switchToLight' : 'switchToDark'],
  );
  if (themeLabel) {
    themeLabel.textContent = translations[currentLanguage][isDark ? 'lightTheme' : 'darkTheme'];
  }
};

const updateThemeColor = () => {
  document.querySelector('meta[name="theme-color"]')?.setAttribute(
    'content',
    document.documentElement.dataset.theme === 'light' ? '#f8f8f5' : '#171d22',
  );
};

updateThemeToggle();
updateThemeColor();

themeToggle?.addEventListener('click', () => {
  const useLightTheme = document.documentElement.dataset.theme !== 'light';
  if (useLightTheme) {
    document.documentElement.dataset.theme = 'light';
  } else {
    delete document.documentElement.dataset.theme;
  }
  localStorage.setItem('theme', useLightTheme ? 'light' : 'dark');
  updateThemeColor();
  updateThemeToggle();
});
